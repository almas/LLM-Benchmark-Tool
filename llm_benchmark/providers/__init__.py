class LocalProvider(BaseProvider):
    """Local provider for OpenAI-compatible APIs (e.g., Ollama, vLLM)."""

    def __init__(self, base_url: str, model: Optional[str] = None, api_key: str = "sk-not-used", **kwargs):
        self.base_url = base_url
        self.model = model
        self.api_key = api_key
        self._client = None
        self._default_model = None
        self._models_fetched = False

    async def _ensure_model(self):
        """Fetch default model from API if not specified."""
        if self.model is not None or self._models_fetched:
            return
        
        try:
            from openai import AsyncOpenAI
            client = AsyncOpenAI(api_key=self.api_key, base_url=self.base_url)
            models = await client.models.list()
            if models.data:
                self.model = models.data[0].id
                logger.info(f"Using default model: {self.model}")
            else:
                self.model = "default"
        except Exception as e:
            logger.warning(f"Could not fetch models from API: {e}. Using 'default' as placeholder.")
            self.model = "default"
        finally:
            self._models_fetched = True

    async def chat_completion(
        self,
        messages: List[Message],
        max_tokens: int = 500,
        temperature: float = 0.7,
        **kwargs
    ) -> BenchmarkTrial:
        import time
        from openai import AsyncOpenAI

        if self._client is None:
            self._client = AsyncOpenAI(api_key=self.api_key, base_url=self.base_url)

        # Fetch default model if not specified
        await self._ensure_model()

        start_time = time.time()
        msg_dicts = [{"role": m.role, "content": m.content} for m in messages]

        try:
            response = await self._client.chat.completions.create(
                model=self.model,
                messages=msg_dicts,
                max_tokens=max_tokens,
                temperature=temperature,
                **kwargs
            )

            elapsed = time.time() - start_time
            content = response.choices[0].message.content if response.choices else ""

            return BenchmarkTrial(
                task_id=response.id if hasattr(response, 'id') else f"local-{int(time.time())}",
                prompt=messages[-1].content if messages else "",
                response=content or "",
                input_tokens=response.usage.prompt_tokens if hasattr(response, 'usage') and response.usage else None,
                output_tokens=response.usage.completion_tokens if hasattr(response, 'usage') and response.usage else None,
                response_time=elapsed,
            )
        except Exception as e:
            elapsed = time.time() - start_time
            return BenchmarkTrial(
                task_id=f"local-error-{int(time.time())}",
                prompt=messages[-1].content if messages else "",
                response="",
                response_time=elapsed,
                error=str(e),
            )

    async def run_benchmark(self, task: BenchmarkTask, config: Dict[str, Any]) -> BenchmarkTrial:
        messages = []
        if task.system_prompt:
            messages.append(Message(role="system", content=task.system_prompt))
        messages.append(Message(role="user", content=task.prompt))
        return await self.chat_completion(
            messages,
            max_tokens=config.get("max_tokens", 500),
            temperature=config.get("temperature", 0.7),
        )

    def get_provider_info(self) -> Dict[str, Any]:
        return {
            "type": ProviderType.LOCAL.value,
            "model": self.model or "default-loaded-model",
            "base_url": self.base_url,
        }


def get_provider(provider_type: ProviderType, **kwargs) -> BaseProvider:
    """Factory function to get the appropriate provider."""
    providers = {
        ProviderType.OPENAI: OpenAIProvider,
        ProviderType.AZURE: AzureProvider,
        ProviderType.LOCAL: LocalProvider,
        ProviderType.DUMMY: DummyProvider,
    }

    provider_class = providers.get(provider_type)
    if provider_class is None:
        raise ValueError(f"Unknown provider type: {provider_type}")

    return provider_class(**kwargs)