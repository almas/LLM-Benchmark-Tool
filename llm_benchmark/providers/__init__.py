"""LLM Provider interface and implementations."""

from abc import ABC, abstractmethod
from typing import List, Dict, Any, Optional
import logging

from llm_benchmark.models import Message, BenchmarkTrial, BenchmarkTask, ProviderType
from llm_benchmark.logger import logger


class BaseProvider(ABC):
    """Abstract base class for LLM providers."""

    @abstractmethod
    async def chat_completion(
        self,
        messages: List[Message],
        max_tokens: int = 500,
        temperature: float = 0.7,
        **kwargs
    ) -> BenchmarkTrial:
        """Generate a chat completion and return a trial result."""
        raise NotImplementedError("Subclasses must implement chat_completion")

    @abstractmethod
    async def run_benchmark(self, task: BenchmarkTask, config: Dict[str, Any]) -> BenchmarkTrial:
        """Run a single benchmark task and return the result."""
        raise NotImplementedError("Subclasses must implement run_benchmark")

    @abstractmethod
    def get_provider_info(self) -> Dict[str, Any]:
        """Return provider information."""
        raise NotImplementedError("Subclasses must implement get_provider_info")


class DummyProvider(BaseProvider):
    """Dummy provider for testing that returns mock responses."""

    def __init__(self, api_key: str = "dummy-key", **kwargs):
        self.api_key = api_key
        self.model = kwargs.get("model", "dummy-model")

    async def chat_completion(
        self,
        messages: List[Message],
        max_tokens: int = 500,
        temperature: float = 0.7,
        **kwargs
    ) -> BenchmarkTrial:
        import time
        import random

        start_time = time.time()

        # Simulate network latency
        response_time = random.uniform(0.5, 2.0)
        await self._simulate_delay(response_time)

        # Generate mock response based on prompt
        prompt = messages[-1].content if messages else ""
        response = self._generate_mock_response(prompt, max_tokens)

        elapsed = time.time() - start_time
        input_tokens = len(prompt.split())
        output_tokens = len(response.split())

        return BenchmarkTrial(
            task_id=f"dummy-{int(time.time())}",
            prompt=prompt,
            response=response,
            input_tokens=input_tokens,
            output_tokens=output_tokens,
            response_time=elapsed,
        )

    async def run_benchmark(self, task: BenchmarkTask, config: Dict[str, Any]) -> BenchmarkTrial:
        """Run a single benchmark task."""
        import time
        import random

        messages = []
        if task.system_prompt:
            messages.append(Message(role="system", content=task.system_prompt))
        messages.append(Message(role="user", content=task.prompt))

        start_time = time.time()

        # Simulate processing time
        response_time = random.uniform(0.5, 2.0)
        await self._simulate_delay(response_time)

        response = self._generate_mock_response(task.prompt, config.get("max_tokens", 500))

        elapsed = time.time() - start_time
        input_tokens = len(task.prompt.split())
        output_tokens = len(response.split())

        return BenchmarkTrial(
            task_id=task.id,
            prompt=task.prompt,
            response=response,
            input_tokens=input_tokens,
            output_tokens=output_tokens,
            response_time=elapsed,
        )

    async def _simulate_delay(self, seconds: float):
        """Simulate a delay without blocking."""
        import asyncio
        await asyncio.sleep(seconds)

    def _generate_mock_response(self, prompt: str, max_tokens: int) -> str:
        """Generate a mock response based on the prompt."""
        responses = [
            f"Based on your question about '{prompt[:50]}...', I can provide the following analysis:\n\n"
            f"This is a simulated response for benchmarking purposes. The actual response from the model "
            f"would depend on the specific model configuration and training data.\n\n"
            f"Key points to consider:\n"
            f"1. The context and domain of the question matter significantly\n"
            f"2. Multiple perspectives should be considered\n"
            f"3. Evidence-based reasoning leads to more reliable conclusions\n\n"
            f"In a real benchmark scenario, this response would contain actual "
            f"model-generated content that reflects the model's true capabilities.",
            f"Here's my analysis regarding: {prompt[:60]}...\n\n"
            f"Response generated by DummyProvider for testing purposes.\n"
            f"This mock response simulates what a real LLM might produce.\n"
            f"The length and structure are designed to mimic realistic output.",
        ]
        import random
        response = random.choice(responses)
        # Truncate to max_tokens roughly
        words = response.split()[:max_tokens]
        return " ".join(words)

    def get_provider_info(self) -> Dict[str, Any]:
        return {
            "type": ProviderType.DUMMY.value,
            "model": self.model,
            "api_key_set": bool(self.api_key),
        }


class OpenAIProvider(BaseProvider):
    """OpenAI API provider."""

    def __init__(self, api_key: str, model: str = "gpt-3.5-turbo", base_url: str = None, **kwargs):
        self.api_key = api_key
        self.model = model
        self.base_url = base_url
        self._client = None

    async def chat_completion(
        self,
        messages: List[Message],
        max_tokens: int = 500,
        temperature: float = 0.7,
        **kwargs
    ) -> BenchmarkTrial:
        import time
        from openai import AsyncOpenAI

        if self._client is None:
            client_kwargs = {"api_key": self.api_key}
            if self.base_url:
                client_kwargs["base_url"] = self.base_url
            self._client = AsyncOpenAI(**client_kwargs)

        start_time = time.time()

        msg_dicts = [{"role": m.role, "content": m.content} for m in messages]

        try:
            response = await self._client.chat.completions.create(
                model=self.model,
                messages=msg_dicts,
                max_tokens=max_tokens,
                temperature=temperature,
                **kwargs
            )

            elapsed = time.time() - start_time
            content = response.choices[0].message.content if response.choices else ""

            return BenchmarkTrial(
                task_id=response.id if hasattr(response, 'id') else f"openai-{int(time.time())}",
                prompt=messages[-1].content if messages else "",
                response=content or "",
                input_tokens=response.usage.prompt_tokens if hasattr(response, 'usage') and response.usage else None,
                output_tokens=response.usage.completion_tokens if hasattr(response, 'usage') and response.usage else None,
                response_time=elapsed,
            )
        except Exception as e:
            elapsed = time.time() - start_time
            return BenchmarkTrial(
                task_id=f"openai-error-{int(time.time())}",
                prompt=messages[-1].content if messages else "",
                response="",
                response_time=elapsed,
                error=str(e),
            )

    async def run_benchmark(self, task: BenchmarkTask, config: Dict[str, Any]) -> BenchmarkTrial:
        messages = []
        if task.system_prompt:
            messages.append(Message(role="system", content=task.system_prompt))
        messages.append(Message(role="user", content=task.prompt))
        return await self.chat_completion(
            messages,
            max_tokens=config.get("max_tokens", 500),
            temperature=config.get("temperature", 0.7),
        )

    def get_provider_info(self) -> Dict[str, Any]:
        return {
            "type": ProviderType.OPENAI.value,
            "model": self.model,
            "base_url": self.base_url or "https://api.openai.com/v1",
        }


